/** A Review run always uses one configured reviewer and one immutable input snapshot. */
export type ReviewScope = "worktree" | "staged" | "branch" | "commit";

/**
 * The custom row id a command-started review's own line is drawn as.
 *
 * `/review` starts a run instead of becoming a prompt, so the SDK transcript has no user
 * message for it. The row is derived from the durable thread's `review.command` — the
 * same rule every other Review row follows — rather than a fabricated SDK entry.
 */
export const REVIEW_COMMAND_TYPE = "fastvibe-review-command";

export type ReviewStartRequest = {
  conversationId: string;
  cwd: string;
  scope: ReviewScope;
  base?: string;
  revision?: string;
  instructions?: string;
  /**
   * The `/review` line this run came from, verbatim. A command starts a review instead of
   * becoming a prompt, so no SDK user message exists — the transcript draws this instead.
   */
  command?: string;
};

export type ReviewFile = {
  path: string;
  status: string;
  oldLines: number;
  newLines: number;
  oldMode?: string;
  newMode?: string;
  skipped?: string;
};

export type ReviewContext = {
  id: string;
  scope: ReviewScope;
  base: string;
  target: string;
  capturedAt: number;
  promptVersion: 1;
  model: string;
  thinkingLevel: string;
  /** Original branch comparison requested by the user, retained for a follow-up review. */
  comparisonBase?: string;
  /** Free-form requirements the person gave for this review run. */
  instructions?: string;
  /** The `/review` line that started this run; absent when the dialog or Git pane did. */
  command?: string;
  files: ReviewFile[];
  /** Repository root; all report locations are relative to this root. */
  root: string;
  /** Includes captured worktree/index content, even when HEAD has not changed. */
  digest: string;
};

export type ReviewFinding = {
  id: string;
  title: string;
  severity: "P0" | "P1" | "P2" | "P3";
  confidence: "high" | "medium";
  category: "correctness" | "contract" | "security" | "performance" | "ui" | "tests";
  location: {
    path: string;
    startLine: number;
    endLine: number;
    side: "old" | "new";
    /** Generated by the host from the snapshot, never trusted model text. */
    snippet?: string;
  };
  trigger: string;
  impact: string;
  evidence: string[];
  recommendation: string;
};

export type ReviewReport = {
  version: 1;
  summary: string;
  findings: ReviewFinding[];
  coverage: {
    reviewedPaths: string[];
    unreviewedPaths: Array<{ path: string; reason: string }>;
  };
};
