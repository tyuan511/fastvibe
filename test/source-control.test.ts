import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { promisify } from "node:util";
import { readGitComparison, readGitDiff, readGitHistory, stageGitFiles, unstageGitFiles, discardGitFiles } from "../src/main/source-control.ts";
const exec = promisify(execFile);

test("source control reads untracked/literal paths and preserves the index when discarding", async (t) => {
  const root = await mkdtemp(join(tmpdir(), "fastvibe-scm-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const git = async (...args: string[]) => (await exec("git", ["-C", root, ...args])).stdout;
  await git("init", "-b", "main");
  assert.deepEqual((await readGitHistory(root)).commits, []);
  await writeFile(join(root, "one.txt"), "initial\n");
  await stageGitFiles(root, ["one.txt"]);
  assert.match(await readGitDiff(root, "one.txt", "last-turn"), /\+initial/);
  await writeFile(join(root, "one.txt"), "initial edited\n");
  await unstageGitFiles(root, ["one.txt"]);
  assert.equal(await readFile(join(root, "one.txt"), "utf8"), "initial edited\n");
  assert.match(await readGitDiff(root, "one.txt"), /\+initial/);
  await stageGitFiles(root, ["one.txt"]);
  await git("-c", "user.name=Test", "-c", "user.email=test@example.com", "commit", "-m", "Initial");
  await writeFile(join(root, "one.txt"), "staged\n");
  await stageGitFiles(root, ["one.txt"]);
  await writeFile(join(root, "one.txt"), "working\n");
  assert.match(await readGitDiff(root, "one.txt", "staged"), /\+staged/);
  assert.match(await readGitDiff(root, "one.txt", "unstaged"), /-staged\n\+working/);
  await discardGitFiles(root, ["one.txt"]);
  assert.equal(await readFile(join(root, "one.txt"), "utf8"), "staged\n");
  assert.equal(await git("show", ":one.txt"), "staged\n");
  await unstageGitFiles(root, ["one.txt"]);
  assert.equal(await readFile(join(root, "one.txt"), "utf8"), "staged\n");
  const literal = " name[1] 中文.txt ";
  await writeFile(join(root, literal), "new literal\n");
  await writeFile(join(root, " name1 中文.txt "), "other\n");
  assert.match(await readGitDiff(root, literal), /\+new literal/);
  const staged = await stageGitFiles(root, [literal]);
  assert.equal(staged.files.find((file) => file.path === literal)?.index, "A");
  assert.equal(staged.files.find((file) => file.path === " name1 中文.txt ")?.index, "?");
  await unstageGitFiles(root, [literal]);
  await discardGitFiles(root, [literal]);
  await assert.rejects(readFile(join(root, literal)), /ENOENT/);
  assert.equal(await readFile(join(root, " name1 中文.txt "), "utf8"), "other\n");
  await assert.rejects(readGitComparison(root), /upstream/);
  await assert.rejects(readGitComparison(root, "--all"), /Invalid commit/);
});

test("history and branch file lists use committed changes, including clean working trees and root commits", async (t) => {
  const root = await mkdtemp(join(tmpdir(), "fastvibe-scm-history-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const git = async (...args: string[]) => (await exec("git", ["-C", root, ...args])).stdout;
  await git("init", "-b", "main");
  await git("config", "user.name", "Test"); await git("config", "user.email", "test@example.com");
  await mkdir(join(root, "src"));
  await writeFile(join(root, "src/a.txt"), "one\n");
  await stageGitFiles(root, undefined, true); await git("commit", "-m", "Initial");
  const initial = (await git("rev-parse", "HEAD")).trim();
  await git("switch", "-c", "feature"); await git("branch", "--set-upstream-to=main");
  await writeFile(join(root, "src/a.txt"), "two\n"); await writeFile(join(root, "src/new\nname.txt"), "new\n");
  await stageGitFiles(root, undefined, true); await git("commit", "-m", "Feature");
  const feature = (await git("rev-parse", "HEAD")).trim();
  assert.equal((await readGitHistory(root)).commits[0].hash, feature);
  assert.equal((await readGitHistory(root, 1)).commits[0].subject, "Initial");
  assert.equal((await readGitHistory(root)).commits[1].parents.length, 0);
  const branch = await readGitComparison(root);
  assert.equal(branch.base, initial);
  assert.deepEqual(branch.files.map((file) => file.path), ["src/a.txt", "src/new\nname.txt"]);
  assert.match(await readGitDiff(root, "src/a.txt", "branch"), /-one\n\+two/);
  assert.deepEqual((await readGitComparison(root, initial)).files.map((file) => file.path), ["src/a.txt"]);
  assert.match(await readGitDiff(root, "src/a.txt", "branch", initial), /\+one/);
  const nested = await readGitComparison(join(root, "src"), feature);
  assert.deepEqual(nested.files.map((file) => file.path), ["a.txt", "new\nname.txt"]);
  assert.match(await readGitDiff(join(root, "src"), "a.txt", "branch", feature), /\+two/);
  await assert.rejects(readGitDiff(root, "a\0b"), /Invalid file/);
});

test("unstaging a rename restores both index paths while keeping working files", async (t) => {
  const root = await mkdtemp(join(tmpdir(), "fastvibe-scm-rename-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const git = async (...args: string[]) => (await exec("git", ["-C", root, ...args])).stdout;
  await git("init", "-b", "main");
  await writeFile(join(root, "old.txt"), "same content\n");
  await stageGitFiles(root, undefined, true);
  await git("-c", "user.name=Test", "-c", "user.email=test@example.com", "commit", "-m", "Initial");
  await git("mv", "old.txt", "new.txt");
  assert.match(await readGitDiff(root, "new.txt", "staged"), /rename from old.txt/);
  const status = await unstageGitFiles(root, ["new.txt"]);
  assert.equal(status.staged, 0);
  assert.equal(await readFile(join(root, "new.txt"), "utf8"), "same content\n");
  assert.equal(await git("show", ":old.txt"), "same content\n");
});

test("history shows real merge topology, local/remote/tag refs and stable pagination tips", async (t) => {
  const root = await mkdtemp(join(tmpdir(), "fastvibe-scm-graph-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const git = async (...args: string[]) => (await exec("git", ["-C", root, ...args])).stdout;
  await git("init", "-b", "main");
  await git("config", "user.name", "Test"); await git("config", "user.email", "test@example.com");
  await writeFile(join(root, "root.txt"), "root\n");
  await stageGitFiles(root, undefined, true); await git("commit", "-m", "Root");
  const first = (await git("rev-parse", "HEAD")).trim();
  await git("tag", "-a", "v1.0", "-m", "Release");
  await git("switch", "-c", "feature");
  await writeFile(join(root, "feature.txt"), "feature\n");
  await stageGitFiles(root, undefined, true); await git("commit", "-m", "Feature", "-m", "Detailed feature description.");
  const feature = (await git("rev-parse", "HEAD")).trim();
  await git("switch", "main");
  await writeFile(join(root, "main.txt"), "main\n");
  await stageGitFiles(root, undefined, true); await git("commit", "-m", "Main");
  await git("merge", "--no-ff", "feature", "-m", "Merge feature");
  const merge = (await git("rev-parse", "HEAD")).trim();
  await git("update-ref", "refs/remotes/origin/main", merge);
  await git("symbolic-ref", "refs/remotes/origin/HEAD", "refs/remotes/origin/main");
  await git("switch", "-c", "unmerged", first);
  await writeFile(join(root, "unmerged.txt"), "side\n");
  await stageGitFiles(root, undefined, true); await git("commit", "-m", "Unmerged");
  const side = (await git("rev-parse", "HEAD")).trim();
  await git("switch", "main");
  const all = await readGitHistory(root);
  const head = all.commits.find((entry) => entry.hash === merge)!;
  assert.equal(head.isHead, true);
  assert.equal(head.parents.length, 2);
  assert.ok(head.refs.some((ref) => ref.kind === "local" && ref.name === "main" && ref.current));
  assert.ok(head.refs.some((ref) => ref.kind === "remote" && ref.name === "origin/main"));
  assert.ok(!head.refs.some((ref) => ref.name === "origin/HEAD"));
  assert.ok(all.commits.find((entry) => entry.hash === first)?.refs.some((ref) => ref.kind === "tag" && ref.name === "v1.0"));
  assert.match(all.commits.find((entry) => entry.hash === feature)!.body, /Detailed feature description/);
  assert.ok(all.commits.some((entry) => entry.hash === side));
  const current = await readGitHistory(root, 0, "current");
  assert.ok(!current.commits.some((entry) => entry.hash === side));
  assert.ok(current.commits.some((entry) => entry.hash === feature));
  assert.deepEqual((await readGitComparison(root, merge)).files.map((file) => file.path), ["feature.txt"]);
  await git("commit", "--allow-empty", "-m", "New head");
  const older = await readGitHistory(root, 1, "all", all.tips);
  assert.deepEqual(older.commits.map((entry) => entry.hash), all.commits.slice(1).map((entry) => entry.hash));
  await assert.rejects(readGitHistory(root, 0, "all", ["--all"]), /Invalid history cursor/);
});

test("normal commits and amendments preserve unstaged content and update only the index", async (t) => {
  const { commitGitChanges } = await import("../src/main/source-control.ts");
  const { collectCommitMessageMaterial, readCommitStatusFiles } = await import("../src/main/workspace-git.ts");
  const root = await mkdtemp(join(tmpdir(), "fastvibe-scm-commit-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const git = async (...args: string[]) => (await exec("git", ["-C", root, ...args])).stdout;
  await git("init", "-b", "main");
  await git("config", "user.name", "Test"); await git("config", "user.email", "test@example.com");
  await assert.rejects(commitGitChanges(root, "", { amend: true }));
  await writeFile(join(root, "tracked.txt"), "base\n");
  await stageGitFiles(root, undefined, true);
  const unborn = await collectCommitMessageMaterial(root, await readCommitStatusFiles(root), true);
  assert.match(unborn[0].patch!, /\+base/);
  await commitGitChanges(root, "Initial");
  await writeFile(join(root, "tracked.txt"), "staged-v2\n");
  await stageGitFiles(root, ["tracked.txt"]);
  await writeFile(join(root, "tracked.txt"), "unstaged-v3\n");
  await writeFile(join(root, "later.txt"), "later\n");
  const material = await collectCommitMessageMaterial(root, await readCommitStatusFiles(root), true);
  assert.equal(material.length, 1);
  assert.equal(material[0].path, "tracked.txt");
  assert.equal(material[0].status, "M ");
  assert.match(material[0].patch!, /\+staged-v2/);
  assert.ok(!material[0].patch!.includes("unstaged-v3"));
  await assert.rejects(commitGitChanges(root, "  "));
  await commitGitChanges(root, "Second");
  assert.equal(await git("show", "HEAD:tracked.txt"), "staged-v2\n");
  assert.equal(await readFile(join(root, "tracked.txt"), "utf8"), "unstaged-v3\n");
  await commitGitChanges(root, "", { amend: true });
  assert.equal((await git("log", "-1", "--format=%s")).trim(), "Second");
  assert.equal((await git("rev-list", "--count", "HEAD")).trim(), "2");
  await stageGitFiles(root, ["later.txt"]);
  await commitGitChanges(root, "Second corrected", { amend: true });
  assert.equal((await git("log", "-1", "--format=%s")).trim(), "Second corrected");
  assert.equal((await git("rev-list", "--count", "HEAD")).trim(), "2");
  assert.equal(await git("show", "HEAD:later.txt"), "later\n");
  assert.equal(await git("show", "HEAD:tracked.txt"), "staged-v2\n");
  assert.equal(await readFile(join(root, "tracked.txt"), "utf8"), "unstaged-v3\n");
});
