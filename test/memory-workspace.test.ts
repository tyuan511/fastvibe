import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { changesBetween, readBaseline, readTree, removeSymlinks, renderWorkspaceDiff, validateArtifacts, writeBaseline } from "../src/main/engine/memory-workspace.ts";

const tmp = (): string => mkdtempSync(join(tmpdir(), "fv-workspace-"));

test("added, modified and deleted files are listed, then shown as a git-style diff", () => {
  const baseline = new Map([["MEMORY.md", "a\nb\nc\nd\ne\nf\ng\n"], ["rollout_summaries/old.md", "old\n"], ["same.md", "same\n"]]);
  const current = new Map([["MEMORY.md", "a\nb\nc\nD\ne\nf\ng\n"], ["rollout_summaries/new.md", "n1\nn2\n"], ["same.md", "same\n"]]);
  assert.deepEqual(changesBetween(baseline, current), [
    { status: "modified", path: "MEMORY.md" },
    { status: "added", path: "rollout_summaries/new.md" },
    { status: "deleted", path: "rollout_summaries/old.md" },
  ]);
  const text = renderWorkspaceDiff(baseline, current);
  assert.match(text, /^# Memory Workspace Diff\n\nGenerated by FastVibe before Phase 2 memory consolidation\. Read this file first and do not edit it\.\n\n## Status\n- modified MEMORY\.md\n- added rollout_summaries\/new\.md\n- deleted rollout_summaries\/old\.md\n\n## Diff\n\n```diff\n/);
  assert.match(text, /diff --git a\/MEMORY\.md b\/MEMORY\.md\n--- a\/MEMORY\.md\n\+\+\+ b\/MEMORY\.md\n@@ -1,7 \+1,7 @@\n a\n b\n c\n-d\n\+D\n e/);
  assert.match(text, /new file mode 100644\n--- \/dev\/null\n\+\+\+ b\/rollout_summaries\/new\.md\n@@ -0,0 \+1,2 @@\n\+n1\n\+n2/);
  assert.match(text, /deleted file mode 100644\n--- a\/rollout_summaries\/old\.md\n\+\+\+ \/dev\/null\n@@ -1,1 \+0,0 @@\n-old/);
  assert.ok(text.endsWith("```\n"));
});

test("nothing changed reads as none", () => {
  const tree = new Map([["a.md", "x\n"]]);
  assert.deepEqual(changesBetween(tree, new Map(tree)), []);
  assert.match(renderWorkspaceDiff(tree, new Map(tree)), /## Status\n- none\n$/);
});

test("far-apart edits are separate hunks; a rewrite beyond the edit limit is shown replaced", () => {
  const lines = Array.from({ length: 60 }, (_, index) => `line ${index}`);
  const edited = [...lines];
  edited[2] = "changed early";
  edited[55] = "changed late";
  const text = renderWorkspaceDiff(new Map([["a.md", `${lines.join("\n")}\n`]]), new Map([["a.md", `${edited.join("\n")}\n`]]));
  assert.equal(text.match(/^@@ /gm)?.length, 2);

  const big = Array.from({ length: 2_000 }, (_, index) => `old ${index}`).join("\n");
  const other = Array.from({ length: 2_000 }, (_, index) => `new ${index}`).join("\n");
  const replaced = renderWorkspaceDiff(new Map([["a.md", `${big}\n`]]), new Map([["a.md", `${other}\n`]]));
  assert.match(replaced, /@@ -1,2000 \+1,2000 @@/);
});

test("the diff really applies: random edits reproduce the new file under git apply", { skip: (() => { try { execFileSync("git", ["--version"], { stdio: "ignore" }); return false; } catch { return true; } })() }, () => {
  let seed = 7;
  const rnd = (n: number): number => { seed = (seed * 1103515245 + 12345) & 0x7fffffff; return seed % n; };
  for (let round = 0; round < 60; round += 1) {
    const before = `${Array.from({ length: 1 + rnd(40) }, () => `line ${rnd(12)}`).join("\n")}\n`;
    let after = before.split("\n").filter(() => rnd(6) !== 0).flatMap((line) => (rnd(8) === 0 ? [line, `new ${rnd(99)}`] : [line])).join("\n");
    if (!after.endsWith("\n")) after += "\n";
    if (after === "\n") after = "x\n";
    const dir = tmp();
    try {
      const text = renderWorkspaceDiff(new Map([["a.md", before]]), new Map([["a.md", after]]));
      writeFileSync(join(dir, "a.md"), before);
      writeFileSync(join(dir, "p.diff"), `${text.slice(text.indexOf("```diff\n") + 8, text.lastIndexOf("```")).replace(/\n$/, "")}\n`);
      execFileSync("git", ["apply", "--whitespace=nowarn", "p.diff"], { cwd: dir, stdio: "pipe" });
      assert.equal(readFileSync(join(dir, "a.md"), "utf8"), after);
    } finally { rmSync(dir, { recursive: true, force: true }); }
  }
});

test("a tree is read without hidden files, the diff file, or anything behind a symlink", async () => {
  const dir = tmp();
  try {
    mkdirSync(join(dir, "rollout_summaries"));
    writeFileSync(join(dir, "MEMORY.md"), "m");
    writeFileSync(join(dir, "rollout_summaries", "a.md"), "a");
    writeFileSync(join(dir, ".hidden"), "h");
    writeFileSync(join(dir, "phase2_workspace_diff.md"), "d");
    const outside = tmp();
    writeFileSync(join(outside, "secret.md"), "secret");
    symlinkSync(outside, join(dir, "link"));
    assert.deepEqual([...(await readTree(dir)).keys()].sort(), ["MEMORY.md", "rollout_summaries/a.md"]);
    assert.equal(await removeSymlinks(dir), 1);
    assert.equal(await removeSymlinks(dir), 0);
    rmSync(outside, { recursive: true, force: true });
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test("a baseline is an exact copy, replaced whole", async () => {
  const dir = tmp();
  try {
    const baseline = join(dir, "baseline");
    await writeBaseline(baseline, new Map([["MEMORY.md", "one"], ["rollout_summaries/a.md", "a"]]));
    assert.deepEqual([...(await readBaseline(baseline)).entries()].sort(), [["MEMORY.md", "one"], ["rollout_summaries/a.md", "a"]]);
    await writeBaseline(baseline, new Map([["MEMORY.md", "two"]]));
    assert.deepEqual([...(await readBaseline(baseline)).entries()], [["MEMORY.md", "two"]]);
    assert.equal((await readBaseline(join(dir, "never"))).size, 0);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test("a consolidation counts only when MEMORY.md exists and the summary starts with v1", async () => {
  const dir = tmp();
  try {
    assert.match(String(await validateArtifacts(dir)), /MEMORY\.md/);
    writeFileSync(join(dir, "MEMORY.md"), "# Task Group: x\n");
    assert.match(String(await validateArtifacts(dir)), /memory_summary\.md was not written/);
    writeFileSync(join(dir, "memory_summary.md"), "## User Profile\n");
    assert.match(String(await validateArtifacts(dir)), /does not start with the line v1/);
    writeFileSync(join(dir, "memory_summary.md"), "v1\n\n## User Profile\n");
    assert.equal(await validateArtifacts(dir), null);
    const outside = tmp();
    symlinkSync(outside, join(dir, "skills"));
    assert.match(String(await validateArtifacts(dir)), /symbolic links/);
    rmSync(outside, { recursive: true, force: true });
  } finally { rmSync(dir, { recursive: true, force: true }); }
});
